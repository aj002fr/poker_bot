"""Interim opponent population: the six styles and four baselines as perturbed families.

This stands in until the real registry (``strategy.population``, another workstream)
lands; :func:`load_population` switches to it by name. It implements
:class:`strategy.eval.population.PartitionSource`.

Each *member* is a family (a style or baseline bot) plus a perturbation vector drawn
from the family's distribution; each table jitters the member's vector again from the
seat's policy seed, so a family is a distribution of behaviours, not one bot. The
perturbation rewrites the inner bot's action with seeded probabilities:

* ``loosen``: a fold facing a bet becomes a call;
* ``tighten``: a call facing a bet becomes a fold;
* ``aggress``: a check or call becomes a bet or raise of ``size`` pots;
* ``passive``: a bet or raise becomes a check or call.

Members are materialized as self-contained bundles (``bot.py`` + the inner bot file +
``params.json``) that import only the arena SDK, so they run in-process and in the
sandbox. Partitions use disjoint seeded draws; validation and holdout draw from wider
distributions than train.
"""

from __future__ import annotations

import hashlib
import json
import random
import shutil
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any

from strategy.eval.population import PARTITIONS, Lineup, OpponentRef, Partition, sample_lineups
from strategy.rules.canonical import canonical_hash

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_DIR = ROOT / "artifacts" / "population" / "interim"
ALL = ("practice_nlhe", "uncertainty_shortdeck", "uncertainty_plo4")
NLHE = ("practice_nlhe",)

FAMILIES: dict[str, tuple[str, tuple[str, ...]]] = {
    "rock": ("style:rock", NLHE),
    "aggressive": ("style:aggressive", NLHE),
    "super_aggressive": ("style:super_aggressive", NLHE),
    "station": ("style:station", NLHE),
    "weak_tight": ("style:weak_tight", NLHE),
    "switcher": ("style:switcher", NLHE),
    "nlhe_heuristic": ("baseline:nlhe_heuristic", NLHE),
    "calling_station": ("baseline:calling_station", ALL),
    "check_fold": ("baseline:check_fold", ALL),
    "legal_random": ("baseline:legal_random", ALL),
}
PERTURB_KEYS = ("loosen", "tighten", "aggress", "passive", "size", "jitter")
# Upper bounds of the uniform draw per key, for train; validation and holdout scale them by WIDEN.
TRAIN_RANGES = {"loosen": (0.0, 0.15), "tighten": (0.0, 0.10), "aggress": (0.0, 0.12), "passive": (0.0, 0.15),
                "size": (0.5, 1.1), "jitter": (0.1, 0.4)}
WIDEN = {"train": 1.0, "validation": 1.5, "holdout": 1.8}
MEMBERS_PER_FAMILY = {"train": 6, "validation": 3, "holdout": 3}

WRAPPER = '''"""Perturbed opponent generated by strategy.search.population (interim registry).

The inner bot's action is rewritten with seeded probabilities; see params.json.
Imports only the arena SDK (and, for styles, the trusted style engine).
"""

import hashlib
import json
import math
from pathlib import Path

from arena.agents.sdk import Action, clamp_raise_to, load_bot, ExplicitStateBot

HERE = Path(__file__).resolve().parent
P = json.loads((HERE / "params.json").read_text(encoding="ascii"))
_SCALE = 1.0 / 18446744073709551616.0


def _u(seed, n):
    h = hashlib.blake2b(f"perturb|{{seed}}|{{n}}".encode(), digest_size=8).digest()
    return int.from_bytes(h, "big") * _SCALE


class Perturbed(ExplicitStateBot):
    def __init__(self):
        self.inner, info = load_bot(HERE / P["inner_file"], module_name="perturbed_inner_" + P["member_hash"][:12])
        self.explicit = info.state_mode == "explicit"
        self.name = "perturbed_" + info.name
        self.rulesets = tuple(info.rulesets)

    def initial_state(self, table):
        inner = self.inner.initial_state(table) if self.explicit else self.inner.start_table(table)
        seed = table.policy_seed
        j = P["jitter"]
        k = {{}}
        for i, key in enumerate(("loosen", "tighten", "aggress", "passive", "size")):
            g = math.sqrt(-2.0 * math.log(max(1e-12, _u(seed, -1 - 2 * i)))) * math.cos(6.283185307 * _u(seed, -2 - 2 * i))
            k[key] = min(1.0, max(0.0, P[key] * math.exp(j * g)))
        return {{"seed": seed, "n": 0, "k": k, "i": inner if self.explicit else None}}

    def decide(self, obs, state):
        if self.explicit:
            raw, inner = self.inner.decide(obs, state["i"])
        else:
            raw, inner = self.inner.decide(obs), None
        if isinstance(raw, dict):
            raw = Action(**{{k: v for k, v in raw.items() if k != "note"}})
        legal, k, n, seed = obs.legal, state["k"], state["n"], state["seed"]
        t = raw.type
        out = raw
        facing = legal.call_amount is not None

        def draw():
            nonlocal n
            n += 1
            return _u(seed, n)

        def bet():
            target = obs.current_bet_to + int(k["size"] * (obs.pot_total + (legal.call_amount or 0)))
            return clamp_raise_to(legal, target)

        if facing and t == "fold" and draw() < k["loosen"]:
            out = Action(type="call")
        elif facing and t == "call":
            if draw() < k["tighten"]:
                out = Action(type="fold")
            elif legal.can_raise and draw() < k["aggress"]:
                out = bet() or raw
        elif t == "check" and legal.can_raise and draw() < k["aggress"]:
            out = bet() or raw
        elif t == "raise_to" and draw() < k["passive"]:
            out = Action(type="call") if facing else Action(type="check")
        if not legal.allows(out):
            out = raw
        return out, {{"seed": seed, "n": n, "k": k, "i": inner}}


def make_bot():
    return Perturbed()
'''


@dataclass(frozen=True)
class Member:
    member_id: str
    family: str
    partition: str
    params: dict[str, float]

    @property
    def inner(self) -> str:
        return FAMILIES[self.family][0]

    @property
    def rulesets(self) -> tuple[str, ...]:
        return FAMILIES[self.family][1]

    def params_hash(self) -> str:
        return canonical_hash({"family": self.family, "inner": self.inner, "params": self.params},
                              domain="interim-member-v1")


def _draw_members(partition: str) -> list[Member]:
    rng = random.Random(f"interim-population-v1|{partition}")
    out = []
    for family in FAMILIES:
        for j in range(MEMBERS_PER_FAMILY[partition]):
            if partition == "train" and j == 0:
                params = {k: 0.0 for k in PERTURB_KEYS[:4]} | {"size": 0.75, "jitter": 0.0}
            else:
                params = {}
                for key in PERTURB_KEYS:
                    lo, hi = TRAIN_RANGES[key]
                    if key in ("size", "jitter"):
                        params[key] = round(rng.uniform(lo, hi), 4)
                    else:
                        params[key] = round(rng.uniform(lo, hi * WIDEN[partition]), 4)
            out.append(Member(f"interim.{partition}.{family}.{j}", family, partition, params))
    return out


def _inner_file(inner: str) -> Path:
    from strategy.eval.policies import resolve_policy

    path = resolve_policy(inner).path
    return path / "bot.py" if path.is_dir() else path


def materialize(member: Member, root: Path = DEFAULT_DIR) -> Path:
    """Write (or reuse) the member's bundle; the directory name carries the content hash."""
    h = member.params_hash()
    out = root / f"{member.member_id}-{h[:10]}"
    if (out / "bot.py").exists():
        return out
    tmp = out.with_name(out.name + ".tmp")
    if tmp.exists():
        shutil.rmtree(tmp)
    tmp.mkdir(parents=True)
    src = _inner_file(member.inner)
    shutil.copyfile(src, tmp / ("inner_" + src.name))
    params = dict(member.params) | {"inner_file": "inner_" + src.name, "member_hash": h, "family": member.family}
    (tmp / "params.json").write_text(json.dumps(params, sort_keys=True, indent=1) + "\n", encoding="ascii")
    (tmp / "bot.py").write_text(WRAPPER.format(), encoding="utf-8")
    try:
        tmp.rename(out)
    except OSError:
        shutil.rmtree(tmp, ignore_errors=True)
    return out


class InterimPopulation:
    """Perturbed style and baseline families. Implements ``PartitionSource``; not the plan's registry."""

    registry_id = "interim-perturbed-families-v1"

    def __init__(self, root: Path | str = DEFAULT_DIR) -> None:
        self.root = Path(root)
        self.members = {p: _draw_members(p) for p in PARTITIONS}

    def registry_hash(self) -> str:
        return canonical_hash({p: [[m.member_id, m.params_hash()] for m in ms] for p, ms in self.members.items()},
                              domain="interim-registry-v1")

    def partition(self, name: str) -> Partition:
        if name not in self.members:
            raise KeyError(f"unknown partition {name!r}; choose from {PARTITIONS}")
        refs = tuple(OpponentRef(m.member_id, m.family, str(materialize(m, self.root)), m.rulesets, m.params_hash())
                     for m in self.members[name])
        return Partition(name, self.registry_id, self.registry_hash(), f"interim-{name}", refs,
                         {"interim": True, "widen": WIDEN[name]})

    def sample_lineups(self, partition: Partition, *, ruleset_id: str, opponents: int, count: int,
                       seed: str) -> list[Lineup]:
        return sample_lineups(partition, ruleset_id=ruleset_id, opponents=opponents, count=count, seed=seed)


@cache
def interim() -> InterimPopulation:
    return InterimPopulation()


def load_population(name: str = "auto") -> Any:
    """``interim``, ``stub``, ``module:attribute``, or ``auto`` (the real registry when present)."""
    from strategy.eval.population import load_partition_source

    if name == "interim":
        return interim()
    if name == "auto":
        try:
            import strategy.population as real  # noqa: F401
        except ImportError:
            return interim()
        for attr in ("default_source", "registry", "REGISTRY", "source"):
            if hasattr(real, attr):
                return load_partition_source(f"strategy.population:{attr}")
        return interim()
    return load_partition_source(name)


def population_digest(source: Any, partition: str) -> dict[str, Any]:
    part = source.partition(partition)
    return {"registry_id": source.registry_id, "registry_hash": source.registry_hash(), "partition": partition,
            "partition_hash": part.partition_hash(), "members": len(part.members),
            "families": sorted({m.family for m in part.members}),
            "member_params_hash": hashlib.sha256("|".join(f"{m.member_id}:{m.params_hash}" for m in part.members)
                                                  .encode()).hexdigest()}
