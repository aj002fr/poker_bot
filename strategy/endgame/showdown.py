"""Loaded showdown tables and the derived arrays the solver multiplies with.

The table for a variant is generated by :mod:`strategy.tables.showdown`. Loading
checks that its provenance names the same ruleset and variant hash, so tables are
never reused across variants.
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache

import numpy as np

from strategy.endgame.classes import HandClasses, hand_classes


class ShowdownTableMissing(FileNotFoundError):
    pass


@dataclass(frozen=True)
class ShowdownModel:
    ruleset_id: str
    classes: HandClasses
    provenance: dict
    prior: np.ndarray
    """Class probability for one dealt hand (combos / total)."""
    cond: np.ndarray
    """``cond[i, j] = P(villain j | hero i)`` with card removal."""
    joint: np.ndarray
    """``joint[i, j] = P(first i, second j)``."""
    p_win: np.ndarray
    p_tie: np.ndarray
    p_lose: np.ndarray
    bucket: np.ndarray
    buckets: int
    bucket_avg: np.ndarray
    """``bucket_avg[b, i]``: class i's share of bucket b (rows sum to 1), for averaging reaches."""
    j3: np.ndarray
    """``j3[a, b, c, k]``: joint probability of buckets a, b, c and three-way result ``codes3[k]``."""
    codes3: tuple[int, ...]
    eq_random: np.ndarray

    @property
    def h(self) -> int:
        return self.prior.shape[0]

    def matrices(self):
        """Conditional (hero-row) and joint win/tie/lose matrices."""
        return (self.cond * self.p_win, self.cond * self.p_tie, self.cond * self.p_lose,
                self.joint * self.p_win, self.joint * self.p_tie, self.joint * self.p_lose)


def from_arrays(ruleset_id: str, prov: dict, a: dict) -> ShowdownModel:
    hc = hand_classes(ruleset_id)
    if prov.get("ruleset_id") != ruleset_id or prov.get("variant_hash") != hc.variant_hash:
        raise ValueError(f"showdown table was built for {prov.get('ruleset_id')} "
                         f"({prov.get('variant_hash')}), not {ruleset_id} ({hc.variant_hash})")
    if tuple(int(k) for k in a["class_keys"]) != hc.keys:
        raise ValueError("showdown table classes do not match the variant's hand classes")
    w2 = a["w2"].astype(np.float64)
    combos = a["class_combos"].astype(np.float64)
    prior = combos / combos.sum()
    cond = w2 / w2.sum(1, keepdims=True)
    joint = w2 / w2.sum()
    pw = a["p_win"].astype(np.float64)
    pt = a["p_tie"].astype(np.float64)
    bucket = a["bucket"].astype(np.int64)
    nb = int(bucket.max()) + 1
    avg = np.zeros((nb, len(prior)))
    avg[bucket, np.arange(len(prior))] = prior
    avg /= avg.sum(1, keepdims=True)
    j3 = a["w3"][..., None] * a["o3"].astype(np.float64)
    j3 /= j3.sum()
    return ShowdownModel(ruleset_id, hc, prov, prior, cond, joint, pw, pt, np.clip(1.0 - pw - pt, 0.0, 1.0),
                         bucket, nb, avg, j3, tuple(int(c) for c in a["codes3"]), a["eq_random"].astype(np.float64))


@lru_cache(maxsize=None)
def load_showdown(ruleset_id: str, directory: str | None = None) -> ShowdownModel:
    from strategy.tables import store
    from strategy.tables.showdown import table_name

    loaded = store.load_arrays(table_name(ruleset_id), directory)
    if loaded is None:
        raise ShowdownTableMissing(f"no showdown table for {ruleset_id}: run "
                                   f"python -m strategy.tables.showdown --ruleset {ruleset_id}")
    return from_arrays(ruleset_id, *loaded)
