"""Policy references: ``baseline:<name>``, ``style:<name>`` or a bot path, with content hashes.

A *salted* arm is the same artifact with its policy random stream re-keyed: the
wrapper replaces ``TableInfo.policy_seed`` with ``sha256(salt | policy_seed)`` and
changes nothing else. Decks, buttons and seats still come from the shared table
seed, so a salted A/A comparison is a true null with independent policy noise.
The wrapper is a self-contained bundle (it imports only the SDK), so it runs in the
sandbox as well as in-process.
"""

from __future__ import annotations

import shutil
from dataclasses import dataclass
from functools import cache
from pathlib import Path

from arena.agents.baselines import BASELINES
from arena.agents.sdk import load_bot
from arena.agents.styles import STYLES, resolve_style, style_artifact_hash
from arena.agents.worker import artifact_hash
from arena.benchmark.runner import Entrant

SALTED_TEMPLATE = '''"""Salted wrapper generated by strategy.eval.policies: the inner bot with a re-keyed policy seed."""

import hashlib
from pathlib import Path

from arena.agents.sdk import ExplicitStateBot, InstanceStateBot, load_bot

SALT = {salt!r}
INNER = Path(__file__).resolve().parent / {inner!r}


def _salted(table):
    seed = hashlib.sha256(f"strategy-salt-v1|{{SALT}}|{{table.policy_seed}}".encode()).hexdigest()[:32]
    return table.model_copy(update={{"policy_seed": seed}})


def make_bot():
    inner, info = load_bot(INNER, module_name="strategy_salted_inner_" + hashlib.sha256(
        f"{{INNER}}|{{SALT}}".encode()).hexdigest()[:12])

    if info.state_mode == "explicit":
        class Salted(ExplicitStateBot):
            def initial_state(self, table):
                return inner.initial_state(_salted(table))

            def decide(self, observation, state):
                return inner.decide(observation, state)
    else:
        class Salted(InstanceStateBot):
            def start_table(self, table):
                return inner.start_table(_salted(table))

            def decide(self, observation):
                return inner.decide(observation)

    Salted.name = info.name
    Salted.rulesets = tuple(info.rulesets)
    return Salted()
'''


@dataclass(frozen=True)
class ResolvedPolicy:
    spec: str
    name: str
    family: str
    path: Path
    artifact_sha256: str
    rulesets: tuple[str, ...]
    builtin: bool
    artifact_bytes: int

    def entrant(self, isolation: str, label: str | None = None) -> Entrant:
        """The runner stages a bundle directory in the sandbox but imports a file in-process."""
        path = self.path / "bot.py" if self.path.is_dir() and isolation == "in_process" else self.path
        return Entrant(name=label or self.name, path=path, builtin=self.builtin)


def _bytes(path: Path) -> int:
    if path.is_file():
        return path.stat().st_size
    return sum(p.stat().st_size for p in path.rglob("*") if p.is_file() and "__pycache__" not in p.parts)


@cache
def _rulesets(path: Path) -> tuple[str, ...]:
    _, info = load_bot(path / "bot.py" if path.is_dir() else path,
                       module_name="strategy_probe_" + artifact_hash(path)[:16])
    return tuple(info.rulesets)


def resolve_policy(spec: str) -> ResolvedPolicy:
    kind, _, name = spec.partition(":")
    if kind == "baseline" and name in BASELINES:
        path = BASELINES[name]
        return ResolvedPolicy(spec, name, name, path, artifact_hash(path), _rulesets(path), True, _bytes(path))
    if kind == "style":
        style = resolve_style(name)
        if style is None:
            raise ValueError(f"unknown style {name!r}; choose from {sorted(STYLES)}")
        path = STYLES[style]
        return ResolvedPolicy(spec, f"style_{style}", style, path, style_artifact_hash(style), _rulesets(path),
                              True, _bytes(path))
    path = Path(name if kind == "path" else spec).resolve()
    if not path.exists():
        raise ValueError(f"policy {spec!r} is not baseline:<name>, style:<name> or an existing bot path")
    return ResolvedPolicy(spec, path.stem if path.is_file() else path.name, "custom", path, artifact_hash(path),
                          _rulesets(path), False, _bytes(path))


def salted_bundle(policy: ResolvedPolicy, salt: str, out_dir: Path) -> ResolvedPolicy:
    """Write (or reuse) a wrapper bundle in ``out_dir`` and resolve it as a policy."""
    if not policy.path.is_file():
        raise ValueError("salted arms support single-file bots only")
    out_dir.mkdir(parents=True, exist_ok=True)
    inner = "inner_" + policy.path.name
    shutil.copyfile(policy.path, out_dir / inner)
    (out_dir / "bot.py").write_text(SALTED_TEMPLATE.format(salt=salt, inner=inner), encoding="utf-8")
    return ResolvedPolicy(f"{policy.spec}#salt={salt}", policy.name, policy.family, out_dir, artifact_hash(out_dir),
                          policy.rulesets, policy.builtin, _bytes(out_dir))
