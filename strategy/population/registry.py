"""Frozen opponent registry with train, validation and holdout partitions.

The registry is a pure function of :data:`REGISTRY_VERSION`, the family priors and
:data:`COUNTS`: member ``i`` of family ``f`` in partition ``P`` is drawn from ``f``'s prior
with seed ``"<version>|<P>|<f>|<i>"``, restricted to ``P``'s latent region
(:mod:`strategy.population.params`). ``registry.lock.json`` freezes every member id and
spec hash, every default lineup-pool hash, the hash of the generated card tables and a
per-variant behaviour fingerprint (:func:`behaviour_fingerprint`); :func:`verify_lock`
(run by the tests) fails if any of them moves. Changing a prior, a count, a rule or the
tables therefore needs a new version and a re-lock
(``python -m strategy.population.registry --write-lock``), never a silent edit.

Split discipline (plan section 4):

* parameter regions are disjoint by construction and checkable from stored parameters;
* seeds are namespaced by partition, so member draws and table seeds never coincide;
* families in :data:`~strategy.population.families.HOLDOUT_ONLY` exist only in holdout;
* lineups containing both families of a :data:`VALIDATION_ONLY_PAIRS` pair never occur in
  train; every validation lineup contains one such pair;
* frozen learner checkpoints and approximate responses enter as :class:`CheckpointSlot`
  entries of a :class:`CheckpointLedger`; train pools use only ``promoted`` slots.

Learners see only opaque entrant names (member ids). Family labels are available to
evaluation reports through :meth:`LineupPool.label`, never to bots.
"""

