REGISTRY_VERSION = "pop-v1"
HERE = Path(__file__).resolve().parent
LOCK_PATH = HERE / "registry.lock.json"
LEDGER_PATH = HERE / "checkpoints.json"

COUNTS: Mapping[str, int] = MappingProxyType({"train": 14, "validation": 3, "holdout": 3})
"""Members per family and partition: 70 / 15 / 15 percent of each family's draws."""
HOLDOUT_ONLY_COUNT = 6
VALIDATION_ONLY_PAIRS: tuple[tuple[str, str], ...] = (
    ("squeezer", "limp_iso"),
    ("trapper", "texture_cbettor"),
    ("icm_cap", "smooth_switcher"),
)
"""Family combinations absent from every train lineup."""
VARIANT_ALIASES = {"nlhe": "practice_nlhe", "shortdeck": "uncertainty_shortdeck", "short_deck": "uncertainty_shortdeck",
                   "plo": "uncertainty_plo4", "plo4": "uncertainty_plo4"}
DEFAULT_OPPONENTS = 7
DEFAULT_LINEUPS = 64
Partition = Literal["train", "validation", "holdout"]


def resolve_variant(variant: str) -> str:
    v = VARIANT_ALIASES.get(variant, variant)
    if v not in RULESET_IDS:
        raise ValueError(f"unknown variant {variant!r}; use one of {RULESET_IDS}")
    return v


def _check_partition(partition: str) -> str:
    if partition not in PARTITIONS:
        raise ValueError(f"unknown partition {partition!r}; use one of {PARTITIONS}")
    return partition


# ------------------------------------------------------------------ members


BOT_TEMPLATE = '''"""Population member {member_id} (registry {version}), generated by strategy.population."""

from strategy.population.policy import PopulationBot

SPEC = {spec}


def make_bot():
    return PopulationBot.from_spec(SPEC)
'''


@dataclass(frozen=True)
class Member:
    member_id: str
    family: str
    partition: str
    index: int
    params: Mapping[str, float]
    version: str = REGISTRY_VERSION

    @property
    def spec(self) -> dict[str, Any]:
        return {"member_id": self.member_id, "family": self.family, "params": dict(self.params),
                "registry": self.version}

    @property
    def hash(self) -> str:
        return canonical_hash(self.spec, domain="pop-member-v1")

    @property
    def region(self) -> int:
        return region_of(FAMILIES[self.family].prior, self.params)

    def make_bot(self) -> PopulationBot:
        return PopulationBot.from_spec(self.spec)

    def write_bot(self, directory: str | Path) -> Path:
        """A self-contained bot bundle ``<directory>/<member_id>/`` (``bot.py`` plus the runtime).

        The bundle carries its own copy of :data:`RUNTIME_FILES`, so a sandboxed worker
        needs nothing from the repository beyond the arena SDK and style engine it already
        preloads, and the bundle's artifact hash covers the code that plays the member.
        """
        path = Path(directory) / self.member_id
        text = BOT_TEMPLATE.format(member_id=self.member_id, version=self.version,
                                   spec=json.dumps(self.spec, sort_keys=True, indent=4))
        _write_if_changed(path / "bot.py", text.encode())
        for rel in RUNTIME_FILES:
            _write_if_changed(path / rel, (REPO / rel).read_bytes())
        return path


REPO = HERE.parents[1]
RUNTIME_FILES = tuple(f"strategy/{rel}" for rel in (
    "__init__.py", "population/__init__.py", "population/policy.py", "population/families.py",
    "population/behaviours.py", "population/cards.py", "population/params.py", "population/data/preflop.json"))
"""What a member needs at decision time; everything else in the package is offline tooling."""


def _write_if_changed(path: Path, data: bytes) -> None:
    if not path.exists() or path.read_bytes() != data:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)


def member_seed(version: str, partition: str, family: str, index: int) -> str:
    return f"{version}|{partition}|{family}|{index}"


def member_id(version: str, partition: str, family: str, index: int) -> str:
    """Opaque and stable: it reveals neither the family nor the partition."""
    digest = hashlib.blake2b(f"pop-member-id|{member_seed(version, partition, family, index)}".encode(),
                             digest_size=6).hexdigest()
    return "pm-" + digest


def counts_for(family: str) -> dict[str, int]:
    if family in HOLDOUT_ONLY:
        return {"train": 0, "validation": 0, "holdout": HOLDOUT_ONLY_COUNT}
    return dict(COUNTS)


# ------------------------------------------------------------------ checkpoints


SlotKind = Literal["learner_checkpoint", "approximate_response"]
SlotStatus = Literal["candidate", "promoted", "retired"]


@dataclass(frozen=True)
class CheckpointSlot:
    """Family 18: a frozen learner checkpoint or trained approximate response.

    The artifact (a bot file or directory with ``bot.py``) is frozen by its
    :func:`arena.agents.worker.artifact_hash`; :meth:`verify` refuses a changed file. A
    slot enters training lineups only once ``status`` is ``promoted`` (its own promotion
    test is over, recorded in ``promotion``).
    """

    slot_id: str
    kind: SlotKind
    partition: str
    path: str
    sha256: str
    rulesets: tuple[str, ...]
    status: SlotStatus = "candidate"
    promotion: str | None = None
    note: str = ""

    def verify(self) -> None:
        actual = artifact_hash(Path(self.path))
        if actual != self.sha256:
            raise ValueError(f"checkpoint {self.slot_id} changed: {actual} != frozen {self.sha256}")

    def write_bot(self, directory: str | Path | None = None) -> Path:
        self.verify()
        return Path(self.path)

    @property
    def hash(self) -> str:
        return canonical_hash({k: v for k, v in asdict(self).items() if k != "path"}, domain="pop-checkpoint-v1")


class CheckpointLedger:
    """An append-only JSON list of :class:`CheckpointSlot` entries."""

    def __init__(self, path: str | Path | None = LEDGER_PATH, slots: Iterable[CheckpointSlot] = ()) -> None:
        self.path = Path(path) if path is not None else None
        self.slots: dict[str, CheckpointSlot] = {}
        if self.path is not None and self.path.exists():
            for raw in json.loads(self.path.read_text()):
                raw["rulesets"] = tuple(raw["rulesets"])
                slot = CheckpointSlot(**raw)
                self.slots[slot.slot_id] = slot
        for slot in slots:
            self.slots[slot.slot_id] = slot

    def register(self, path: str | Path, *, kind: SlotKind, partition: str, rulesets: Sequence[str],
                 note: str = "") -> CheckpointSlot:
        _check_partition(partition)
        p = Path(path).resolve()
        digest = artifact_hash(p)
        slot_id = "ck-" + digest[:12]
        slot = CheckpointSlot(slot_id, kind, partition, str(p), digest, tuple(rulesets), note=note)
        old = self.slots.get(slot_id)
        if old is not None:
            if (old.partition, old.kind) != (partition, kind):
                raise ValueError(f"checkpoint {slot_id} is already registered as {old.kind} in {old.partition}")
            return old
        self.slots[slot_id] = slot
        self._save()
        return slot

    def promote(self, slot_id: str, evidence: str) -> CheckpointSlot:
        """Mark a checkpoint promoted after its own promotion test (``evidence``: a run id)."""
        old = self.slots[slot_id]
        old.verify()
        if old.status == "retired":
            raise ValueError(f"checkpoint {slot_id} is retired")
        new = CheckpointSlot(**{**asdict(old), "status": "promoted", "promotion": evidence})
        self.slots[slot_id] = new
        self._save()
        return new

    def retire(self, slot_id: str, note: str) -> CheckpointSlot:
        old = self.slots[slot_id]
        new = CheckpointSlot(**{**asdict(old), "status": "retired", "note": note})
        self.slots[slot_id] = new
        self._save()
        return new

    def eligible(self, partition: str, variant: str) -> list[CheckpointSlot]:
        return [s for s in self.slots.values()
                if s.partition == partition and s.status == "promoted" and variant in s.rulesets]

    def _save(self) -> None:
        if self.path is None:
            return
        slots = sorted(self.slots.values(), key=lambda s: s.slot_id)
        data = [dict(asdict(s), rulesets=list(s.rulesets)) for s in slots]
        self.path.write_text(json.dumps(data, indent=2) + "\n")


# ------------------------------------------------------------------ lineups


@dataclass(frozen=True)
class Lineup:
    lineup_id: str
    partition: str
    variant: str
    entries: tuple[str, ...]
    """Member ids and checkpoint slot ids, in seat order before rotation."""

    @property
    def hash(self) -> str:
        return canonical_hash([self.partition, self.variant, list(self.entries)], domain="pop-lineup-v1")


@dataclass(frozen=True)
class LineupPool:
    """The opponents an evaluation or training run may face, for one partition and variant."""

    partition: str
    variant: str
    lineups: tuple[Lineup, ...]
    members: Mapping[str, Member]
    checkpoints: Mapping[str, CheckpointSlot]
    registry_hash: str
    seed_namespace: str
    _labels: Mapping[str, str] = field(repr=False, default_factory=dict)

    @property
    def hash(self) -> str:
        return canonical_hash({"partition": self.partition, "variant": self.variant, "registry": self.registry_hash,
                               "lineups": [lu.hash for lu in self.lineups],
                               "checkpoints": sorted(c.hash for c in self.checkpoints.values()),
                               "seeds": self.seed_namespace}, domain="pop-pool-v1")

    def table_seeds(self, count: int, start: int = 0) -> list[str]:
        """Table seeds reserved for this partition and variant (disjoint from every other pool)."""
        return derive_seeds(self.seed_namespace, start + count)[start:]

    def entry_ids(self) -> list[str]:
        return sorted({e for lu in self.lineups for e in lu.entries})

    def bots(self, lineup: Lineup) -> list[tuple[str, object]]:
        """``(entrant name, bot)`` for in-process play. Checkpoint slots load their artifact."""
        from arena.agents.sdk import load_bot

        out: list[tuple[str, object]] = []
        for e in lineup.entries:
            if e in self.members:
                out.append((e, self.members[e].make_bot()))
            else:
                out.append((e, load_bot(self.checkpoints[e].write_bot(), module_name=f"pop_ck_{e}")[0]))
        return out

    def entrants(self, lineup: Lineup, directory: str | Path) -> list[tuple[str, Path]]:
        """``(entrant name, bot bundle)`` for sandboxed runs, e.g. ``arena.benchmark.runner.Entrant``."""
        d = Path(directory)
        d.mkdir(parents=True, exist_ok=True)
        return [(e, self.members[e].write_bot(d) if e in self.members else self.checkpoints[e].write_bot(d))
                for e in lineup.entries]

    def label(self, entry_id: str) -> str:
        """The family (or checkpoint kind) behind an entrant, for evaluation reports only."""
        return self._labels[entry_id]

    def manifest(self) -> dict[str, Any]:
        return {"partition": self.partition, "variant": self.variant, "pool_hash": self.hash,
                "registry_hash": self.registry_hash, "registry_version": REGISTRY_VERSION,
                "seed_namespace": self.seed_namespace, "lineups": len(self.lineups),
                "entries": {e: (self.members[e].hash if e in self.members else self.checkpoints[e].sha256)
                            for e in self.entry_ids()}}


# ------------------------------------------------------------------ registry


class Registry:
    def __init__(self, version: str = REGISTRY_VERSION, ledger: CheckpointLedger | None = None) -> None:
        self.version = version
        self.ledger = ledger if ledger is not None else CheckpointLedger(LEDGER_PATH)
        self.members: dict[str, Member] = {}
        for fam in FAMILY_LIST:
            for partition, n in counts_for(fam.id).items():
                for i in range(n):
                    mid = member_id(version, partition, fam.id, i)
                    params = fam.prior.sample(member_seed(version, partition, fam.id, i), partition)
                    self.members[mid] = Member(mid, fam.id, partition, i, MappingProxyType(params), version)

    @property
    def hash(self) -> str:
        return canonical_hash({"version": self.version, "members": {m: x.hash for m, x in sorted(self.members.items())},
                               "tables": tables_hash()}, domain="pop-registry-v1")

    def partition(self, partition: str) -> list[Member]:
        _check_partition(partition)
        return [m for m in self.members.values() if m.partition == partition]

    def families_in(self, partition: str) -> list[str]:
        return sorted({m.family for m in self.partition(partition)})

    def lineup_pool(self, partition: str, variant: str, *, opponents: int = DEFAULT_OPPONENTS,
                    lineups: int = DEFAULT_LINEUPS, checkpoints: bool = True) -> LineupPool:
        """``checkpoints=False`` ignores the ledger (the locked default pools do)."""
        _check_partition(partition)
        variant = resolve_variant(variant)
        if not 1 <= opponents <= 7:
            raise ValueError("opponents must be 1..7 (the arena seats at most 8)")
        by_family: dict[str, list[Member]] = {}
        for m in self.partition(partition):
            by_family.setdefault(m.family, []).append(m)
        slots = {c.slot_id: c for c in self.ledger.eligible(partition, variant)} if checkpoints else {}
        rng = random.Random(f"{self.version}|{partition}|{variant}|lineups|{opponents}")
        ids = {f: [m.member_id for m in ms] for f, ms in by_family.items()}
        out: list[Lineup] = []
        for k in range(lineups):
            entries = draw_entries(rng, partition, ids, sorted(slots), opponents)
            lid = f"lu-{partition[:2]}-{variant.split('_')[-1]}-{opponents}-{k:03d}"
            out.append(Lineup(lid, partition, variant, tuple(entries)))
        used = {e for lu in out for e in lu.entries}
        labels = {e: self.members[e].family for e in used if e in self.members}
        labels.update({e: slots[e].kind for e in used if e in slots})
        return LineupPool(partition, variant, tuple(out),
                          MappingProxyType({e: self.members[e] for e in used if e in self.members}),
                          MappingProxyType({e: slots[e] for e in used if e in slots}),
                          self.hash, f"{self.version}|{partition}|{variant}|tables", MappingProxyType(labels))

    def lock(self) -> dict[str, Any]:
        pools = {f"{p}/{v}": self.lineup_pool(p, v, checkpoints=False).hash for p in PARTITIONS for v in RULESET_IDS}
        return {
            "version": self.version,
            "registry_hash": self.hash,
            "tables_sha256": tables_hash(),
            "partition_bins": {p: sorted(b) for p, b in PARTITION_BINS.items()},
            "holdout_only": list(HOLDOUT_ONLY),
            "validation_only_pairs": [list(p) for p in VALIDATION_ONLY_PAIRS],
            "members": {m.member_id: {"family": m.family, "partition": m.partition, "index": m.index, "hash": m.hash}
                        for m in sorted(self.members.values(), key=lambda m: (m.family, m.partition, m.index))},
            "default_pools": pools,
            "behaviour": {v: behaviour_fingerprint(self, v) for v in RULESET_IDS},
        }


CHECKPOINT_SEAT_P = 0.5
"""Chance that a lineup's last seat is a promoted checkpoint, when the partition has any."""


def draw_entries(rng: random.Random, partition: str, members: Mapping[str, Sequence[str]], checkpoints: Sequence[str],
                 n: int) -> list[str]:
    """``n`` entry ids: distinct families under the partition's rules, one member each.

    ``members`` maps family to member ids. With ``checkpoints``, the last seat is a
    checkpoint slot with probability :data:`CHECKPOINT_SEAT_P`.
    """
    chosen = _choose_families(rng, partition, sorted(members), n)
    entries = [members[f][rng.randrange(len(members[f]))] for f in chosen]
    forced = {"validation": 2, "holdout": 1}.get(partition, 0)
    if checkpoints and n > forced and rng.random() < CHECKPOINT_SEAT_P:
        entries[-1] = checkpoints[rng.randrange(len(checkpoints))]
    return entries


def _choose_families(rng: random.Random, partition: str, fams: list[str], n: int) -> list[str]:
    pairs = [p for p in VALIDATION_ONLY_PAIRS if p[0] in fams and p[1] in fams]
    for _ in range(1000):
        chosen: list[str] = []
        if partition == "validation" and pairs and n >= 2:
            chosen = list(pairs[rng.randrange(len(pairs))])
        elif partition == "holdout":
            withheld = [f for f in HOLDOUT_ONLY if f in fams]
            if withheld:
                chosen = [withheld[rng.randrange(len(withheld))]]
        rest = [f for f in fams if f not in chosen]
        rng.shuffle(rest)
        need = n - len(chosen)
        chosen += (rest * (need // max(1, len(rest)) + 1))[:need]
        if partition == "train" and any(a in chosen and b in chosen for a, b in VALIDATION_ONLY_PAIRS):
            continue
        return chosen[:n]
    raise RuntimeError("could not build a lineup under the partition constraints")


def tables_hash() -> str:
    return hashlib.sha256(cards.DATA.read_bytes()).hexdigest()


FINGERPRINT_CONFIG = {"hand_cap": 40, "hands_per_level": 5}


def behaviour_fingerprint(registry: Registry, variant: str) -> str:
    """Hash of every action at short seeded tables seating the first member of each family.

    Member hashes freeze parameters; this freezes the code that plays them, so a change to
    a rule, hook or card table that alters any decision also needs a new version.
    """
    from strategy.population.measure import play

    firsts: dict[str, Member] = {}
    for m in sorted(registry.members.values(), key=lambda m: (PARTITIONS.index(m.partition), m.index)):
        firsts.setdefault(m.family, m)
    seats = [firsts[f.id] for f in FAMILY_LIST]
    seats += seats[: -len(seats) % 8]
    actions: list[list[Any]] = []
    for t in range(len(seats) // 8):
        lineup = seats[8 * t: 8 * t + 8]
        table, _ = play([(m.member_id, m.make_bot()) for m in lineup], f"{registry.version}|fingerprint|{variant}|{t}",
                        variant, FINGERPRINT_CONFIG)
        actions += [[t, e.data["seat"], e.data["action"]["type"], e.data["action"].get("amount")]
                    for e in table.log if e.type == "ActionApplied"]
    return canonical_hash(actions, domain="pop-behaviour-v1")


_DEFAULT: Registry | None = None


def default_registry() -> Registry:
    global _DEFAULT
    if _DEFAULT is None:
        _DEFAULT = Registry()
    return _DEFAULT


def get_lineup_pool(partition: Partition | str, variant: str, *, opponents: int = DEFAULT_OPPONENTS,
                    lineups: int = DEFAULT_LINEUPS, registry: Registry | None = None) -> LineupPool:
    """Opponent lineups for ``partition`` (train / validation / holdout) and a variant.

    ``variant`` is a ruleset id (``practice_nlhe``, ``uncertainty_shortdeck``,
    ``uncertainty_plo4``) or an alias (``nlhe``, ``shortdeck``, ``plo4``). The pool is
    deterministic: the same arguments and registry version give the same lineups, seeds
    and :attr:`LineupPool.hash`.
    """
    return (registry or default_registry()).lineup_pool(partition, variant, opponents=opponents, lineups=lineups)


def verify_lock(path: Path = LOCK_PATH, registry: Registry | None = None) -> None:
    frozen = json.loads(path.read_text())
    current = (registry or default_registry()).lock()
    if frozen != current:
        diff = sorted(k for k in set(frozen) | set(current) if frozen.get(k) != current.get(k))
        raise AssertionError(f"registry differs from {path.name} in {diff}: bump REGISTRY_VERSION and re-lock")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write-lock", action="store_true")
    args = ap.parse_args(argv)
    lock = Registry(ledger=CheckpointLedger(None)).lock()
    if args.write_lock:
        LOCK_PATH.write_text(json.dumps(lock, indent=1, sort_keys=True) + "\n")
        print(f"wrote {LOCK_PATH} ({len(lock['members'])} members, registry {lock['registry_hash'][:12]})")
    else:
        print(json.dumps({k: v for k, v in lock.items() if k != "members"}, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
